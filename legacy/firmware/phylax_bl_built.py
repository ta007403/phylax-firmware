#!/usr/bin/env python3
"""PHYLAX Blocks - the hash of the PHYLAX bootloader built with this firmware.

    phylax_bl_built.py BOOTLOADER.bin|-   ->  phylax_bl_built.h

With a bootloader (PHYLAX_SIGNING=1 builds, where ../bootloader is the PHYLAX
bootloader), defines PHYLAX_BL_BUILT_HASH: memory_bootloader_hash() of it,
i.e. SHA256(SHA256(32 KiB, zero padded)) as in bl_data.py. PHYLAX firmware
from the same build then always knows its own bootloader (bl_check.c).
With "-", defines nothing.
"""

import sys
from hashlib import sha256

src = sys.argv[1]
lines = ["// generated by phylax_bl_built.py, do not edit\n"]
if src != "-":
    data = open(src, "rb").read()
    if len(data) > 32768:
        raise SystemExit("bootloader has to be smaller than 32768 bytes")
    data += b"\x00" * (32768 - len(data))
    h = sha256(sha256(data).digest()).digest()
    esc = "".join(f"\\x{b:02x}" for b in h)
    lines.append(f'#define PHYLAX_BL_BUILT_HASH "{esc}"\n')
    print("PHYLAX bootloader hash (for phylax_bl_hashes.h):", h.hex())
open("phylax_bl_built.h", "wt").writelines(lines)
